// Generate the tiny blurred previews the site shows while a photo loads.
//
// Usage: npm run photos:blur
//
// Reads every JPEG under public/images/projects, shrinks it to 20 px wide and
// writes the results to src/content/photo-blur.ts as data URIs (about 0.5 KB
// each). Run it after adding, replacing or re-exporting a project photo.

import { execFileSync } from "node:child_process";
import { mkdtempSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const SOURCE_DIR = "public/images/projects";
const OUTPUT = "src/content/photo-blur.ts";
const WIDTH = 20;

const tmp = mkdtempSync(join(tmpdir(), "blur"));
const entries = listPhotos(SOURCE_DIR)
  .sort()
  .map((file) => {
    const small = join(tmp, file.replaceAll("/", "_"));
    execFileSync("sips", ["-Z", String(WIDTH), "-s", "format", "jpeg", "-s", "formatOptions", "60", file, "--out", small], { stdio: "ignore" });
    const publicPath = file.replace(/^public/, "");
    return `  "${publicPath}": "data:image/jpeg;base64,${readFileSync(small).toString("base64")}",`;
  });

writeFileSync(
  OUTPUT,
  `/**
 * Tiny blurred previews, one per project photo, shown while the full photo
 * loads so a section never flashes empty. Generated by
 * scripts/make-blur-placeholders.mjs (npm run photos:blur); do not edit.
 */
export const PHOTO_BLUR: Readonly<Record<string, string>> = {
${entries.join("\n")}
};
`,
);
console.log(`${OUTPUT}: ${entries.length} previews`);

function listPhotos(dir) {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) return listPhotos(path);
    return name.toLowerCase().endsWith(".jpg") ? [path] : [];
  });
}
